"""
Module: verifier.py
Stage 4: Response Synthesis, Evidence Verification, and Traceable Response

Verifies the faithfulness of the draft generated by the Synthesizer:
1. Splits the Markdown draft into atomic claims by sentence or line.
2. Cross-references each claim against the evidence it cites ([1], [2]...).
3. Assigns a ClaimStatus: SUPPORTED | CONTRADICTED | UNVERIFIED.
4. Computes faithfulness_score and VerificationStatus according to thresholds in schema_response.py.

Defaults to lexical overlap (unigram + bigram) so it can run offline without a model.
When the response and source documents are in different languages (e.g., Vietnamese answer, English OWASP docs),
pass a multilingual embedding-based `similarity_fn` for accurate cross-lingual verification.

Conforms to VerifierProtocol in rag_orchestrator.py:
    verify(draft, evidence_list) -> VerificationReportSchema
"""


"""
Module: verifier.py
Stage 4: Response Synthesis, Evidence Verification, and Traceable Response
Role: BAO (Evidence Verification)

Verify faithfulness of the draft generated by Synthesizer:
1. Split Markdown draft into atomic claims by sentence / line.
2. Cross-check each claim against its cited evidence ([1], [2]...).
3. Assign ClaimStatus: SUPPORTED | CONTRADICTED | UNVERIFIED.
4. Compute faithfulness_score and VerificationStatus according to schema_response.py thresholds.

Uses lexical overlap (unigram + bigram) by default for offline execution without models.
When answers and documents are in different languages (e.g. Vietnamese answers, English OWASP docs),
pass multilingual embedding-based `similarity_fn` for reliable results.

Interface complies with VerifierProtocol in rag_orchestrator.py:
    verify(draft, evidence_list) -> VerificationReportSchema
"""


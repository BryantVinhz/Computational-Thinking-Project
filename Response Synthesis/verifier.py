SimilarityFn = Callable[[str, str], float]

# Overall thresholds matching VerificationStatus docstring.
PASSED_THRESHOLD = 0.8
WARNING_THRESHOLD = 0.5
DEFAULT_SUPPORT_THRESHOLD = 0.50
MIN_CLAIM_TOKENS = 3
SNIPPET_MAX_CHARS = 300
SEMANTIC_SUPPORT_THRESHOLD = 0.50
ADVISORY_MARKER = "general knowledge advisory"

_TAG_RE = re.compile(r"\[(\d+)\]")
_TOKEN_RE = re.compile(r"\w+", re.UNICODE)
_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?;])\s+")
_ONLY_TAGS_RE = re.compile(r"^(?:\s*\[\d+\]\s*[.,;:]?)+$")
_LIST_MARKER_RE = re.compile(r"^\s*(?:[-*+•]|\d+[.)])\s+")
_TABLE_SEPARATOR_RE = re.compile(r"^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)*\|?\s*$")
_MD_EMPHASIS_RE = re.compile(r"(\*\*|__|\*|_|`)")

# Negation tokens used for contradiction detection heuristic (Vietnamese + English).
NEGATION_TOKENS = frozenset({
    "không", "chẳng", "chưa", "đừng", "chớ", "cấm",
    "not", "no", "never", "cannot", "without", "nor", "neither",
})

# Common stopwords: excluded from token set so score reflects content rather than grammar.
# Note: DOES NOT contain negation tokens, so they still participate in matching.
STOPWORDS = frozenset({
    # Vietnamese
    "và", "là", "của", "các", "những", "được", "bị", "cho", "với", "trong", "khi", "này",
    "đó", "để", "một", "có", "thì", "mà", "từ", "theo", "như", "cũng", "đã", "sẽ", "đang",
    "về", "ra", "vào", "tại", "nên", "do", "bởi", "hay", "hoặc", "nếu", "vì", "nhưng",
    # English
    "the", "a", "an", "and", "or", "of", "to", "in", "on", "for", "with", "is", "are", "be",
    "by", "as", "at", "it", "this", "that", "these", "those", "from", "can", "should", "was",
    "were", "has", "have", "which", "its", "into",
})

DISCLAIMER_PATTERNS = [
    r"do chuyên gia minh họa",
    r"không nằm trong tài liệu",
    r"not part of the cited documents",
    r"illustrative code provided by",
    r"hypothetical vulnerable code",
    r"^(dưới đây là|sau đây là|như đã nêu|tóm lại|nhìn chung)",
    r"^(below are|as mentioned|in summary|the following are)",
]

def _is_disclaimer_or_filler(text: str) -> bool:
    t = text.lower().strip()
    return any(re.search(p, t) for p in DISCLAIMER_PATTERNS)

@dataclass
class ExtractedClaim:
    """An atomic claim extracted from the draft."""
    text: str               # Content with citation tags and Markdown formatting stripped
    tags: list[str]         # Citation tags attached to claim, e.g. ["[1]", "[2]"]
    is_advisory: bool       # Belongs to General Knowledge Advisory section (HYBRID)



# Text processing utilities
def _tokens(text: str) -> list[str]:
    normalized = unicodedata.normalize("NFC", text.lower())
    return [t for t in _TOKEN_RE.findall(normalized) if not t.isdigit()]


def _content_tokens(text: str) -> list[str]:
    return [t for t in _tokens(text) if t not in STOPWORDS]


def _bigrams(tokens: list[str]) -> set[tuple[str, str]]:
    return set(zip(tokens, tokens[1:]))


def lexical_support_score(claim: str, passage: str) -> float:
    """
    Proportion of claim content appearing in the passage (0.0 -> 1.0).

    Combines unigram recall and bigram recall: unigrams alone can match easily;
    bigrams preserve compound terms and phrases.
    """
    claim_tokens = _content_tokens(claim)
    if not claim_tokens:
        return 0.0
    passage_tokens = _content_tokens(passage)
    passage_set = set(passage_tokens)
    unigram_recall = sum(t in passage_set for t in claim_tokens) / len(claim_tokens)

    claim_bigrams = _bigrams(claim_tokens)
    if not claim_bigrams:
        return unigram_recall
    bigram_recall = len(claim_bigrams & _bigrams(passage_tokens)) / len(claim_bigrams)
    return 0.5 * unigram_recall + 0.5 * bigram_recall


def _has_negation(text: str) -> bool:
    return any(t in NEGATION_TOKENS for t in _tokens(text))


def _split_sentences(text: str) -> list[str]:
    return [s.strip() for s in _SENTENCE_SPLIT_RE.split(text) if s.strip()]


def _clean_markdown(line: str) -> str:
    line = _LIST_MARKER_RE.sub("", line)
    line = _MD_EMPHASIS_RE.sub("", line)
    return line.strip()


def _truncate(text: str, max_chars: int = SNIPPET_MAX_CHARS) -> str:
    flat = " ".join(text.split())
    return flat if len(flat) <= max_chars else f"{flat[:max_chars].rsplit(' ', 1)[0]}…"



# Claim Extraction
def extract_claims(draft_answer: str, min_tokens: int = MIN_CLAIM_TOKENS) -> list[ExtractedClaim]:
    """
    Split Markdown draft into atomic claims.

    Skips: headings (#), horizontal rules, code blocks, table headers and separators,
    note lines enclosed entirely in parentheses, and fragments shorter than min_tokens.
    Each table row is treated as a claim. Citation tags standing alone after punctuation
    (e.g.: "... input. [1]") are attached to the preceding sentence.
    """
    lines = (draft_answer or "").splitlines()
    claims: list[ExtractedClaim] = []
    in_code_block = False
    in_advisory = False

    for idx, raw_line in enumerate(lines):
        line = raw_line.strip()
        if line.startswith("```"):
            in_code_block = not in_code_block
            continue
        if in_code_block or not line:
            continue
        if line.startswith("#"):
            in_advisory = ADVISORY_MARKER in line.lower()
            continue
        if re.fullmatch(r"[-*_]{3,}", line) or _TABLE_SEPARATOR_RE.match(line):
            continue
        if line.startswith("|"):
            next_line = lines[idx + 1].strip() if idx + 1 < len(lines) else ""
            if _TABLE_SEPARATOR_RE.match(next_line):
                continue  # table header
            # Join with comma (not ';') so sentence splitter preserves row as one claim.
            line = ", ".join(cell.strip() for cell in line.strip("|").split("|") if cell.strip())
        line = _clean_markdown(line)
        if line.startswith("(") and line.endswith(")"):
            continue  # note line, e.g.: "(Note: ...)"

        segments: list[str] = []
        for sentence in _split_sentences(line):
            if segments and _ONLY_TAGS_RE.match(sentence):
                segments[-1] = f"{segments[-1]} {sentence}"
            else:
                segments.append(sentence)

        for segment in segments:
            tags = list(dict.fromkeys(f"[{n}]" for n in _TAG_RE.findall(segment)))
            text = " ".join(_TAG_RE.sub(" ", segment).split()).strip(" .,;:")
            if _is_disclaimer_or_filler(text):
                continue
            
            if len(_content_tokens(text)) < min_tokens:
                continue
            claims.append(ExtractedClaim(text=text, tags=tags, is_advisory=in_advisory))

    return claims

SEMANTIC_SUPPORT_THRESHOLD = 0.60


class MultilingualSemanticSimilarity:
    """
    Cross-lingual cosine similarity (Vietnamese claim vs English evidence) with a multilingual encoder.

    The model is loaded once. If it cannot be loaded, calls raise RuntimeError instead of silently
    degrading to lexical overlap, which scores ~0 across languages and fails every grounded answer.
    Embeddings are cached per text because the verifier scores each claim against every evidence sentence.
    """

    def __init__(
        self,
        model_name: str = "BAAI/bge-m3",
        device: str = "cpu",
        model: Any | None = None,
        max_chars: int = 2000,
        cache_size: int = 4096,
    ):
        self.model_name = model_name
        self.device = device
        self.max_chars = max_chars
        self.cache_size = cache_size
        self._model = model
        self._load_error: Exception | None = None
        self._cache: dict[str, Any] = {}

    def _get_model(self) -> Any:
        if self._model is not None:
            return self._model
        if self._load_error is not None:
            raise RuntimeError(f"Semantic verifier model unavailable: {self._load_error}") from self._load_error
        try:
            from sentence_transformers import SentenceTransformer
            self._model = SentenceTransformer(self.model_name, device=self.device)
        except Exception as e:
            self._load_error = e
            raise RuntimeError(f"Semantic verifier model unavailable: {e}") from e
        return self._model

    def _embed(self, text: str) -> Any:
        key = text[: self.max_chars]
        vector = self._cache.get(key)
        if vector is None:
            vector = self._get_model().encode([key], normalize_embeddings=True, show_progress_bar=False)[0]
            if len(self._cache) >= self.cache_size:
                self._cache.pop(next(iter(self._cache)))
            self._cache[key] = vector
        return vector

    def __call__(self, claim: str, passage: str) -> float:
        if not claim.strip() or not passage.strip():
            return 0.0
        cosine = float((self._embed(claim) * self._embed(passage)).sum())
        return max(0.0, min(1.0, cosine))



# Verifier
class EvidenceVerifier:
    """Verify claims against evidence and assemble VerificationReportSchema."""

    def __init__(
        self,
        similarity_fn: SimilarityFn | None = None,
        support_threshold: float = DEFAULT_SUPPORT_THRESHOLD,
        min_claim_tokens: int = MIN_CLAIM_TOKENS,
    ):
        """
        Args:
            similarity_fn: Function (claim, passage) -> score 0..1. Defaults to lexical_support_score.
            support_threshold: Minimum score for a claim to be considered supported.
            min_claim_tokens: Minimum content tokens for text fragment to be considered a claim.
        """
        self.similarity_fn = similarity_fn or lexical_support_score
        self.support_threshold = support_threshold
        self.min_claim_tokens = min_claim_tokens

    def _best_match(self, claim_text: str, evidence: dict[str, Any]) -> tuple[float, str]:
        """Highest evidence support score for claim, along with best matching sentence as snippet."""
        text = evidence.get("text_content") or ""
        if not text.strip():
            return 0.0, ""
        
        # Detecting the language of the claim
        c_lang = detect_language(claim_text)
        
        # If the claim is in Vietnamese and the evidence is in English -> semantic embedding is required
        if c_lang == "vi" and hasattr(self, "semantic_fn") and self.semantic_fn:
            chunk_score = self.semantic_fn(claim_text, text)
        else:
            chunk_score = self.similarity_fn(claim_text, text)
            

        best_sentence, best_sentence_score = "", -1.0
        for sentence in _split_sentences(text):
            if c_lang == "vi" and hasattr(self, "semantic_fn") and self.semantic_fn:
                score = self.semantic_fn(claim_text, sentence)
            else:
                score = self.similarity_fn(claim_text, sentence)
            if score > best_sentence_score:
                best_sentence, best_sentence_score = sentence, score
        return max(chunk_score, best_sentence_score), best_sentence or text

    def _verify_claim(
        self,
        claim_id: str,
        claim: ExtractedClaim,
        evidence_by_tag: dict[str, dict[str, Any]],
        warnings: list[str],
    ) -> ClaimVerificationResult:
        cited_tag = "".join(claim.tags) or None

        if claim.is_advisory:
            return ClaimVerificationResult(
                claim_id=claim_id,
                claim_text=claim.text,
                cited_tag=cited_tag,
                status=ClaimStatus.UNVERIFIED,
                confidence_score=0.0,
                explanation="General Knowledge Advisory (HYBRID): not compared with evidence, excluded from faithfulness.",
            )

        valid_tags = [t for t in claim.tags if t in evidence_by_tag]
        invalid_tags = [t for t in claim.tags if t not in evidence_by_tag]
        if invalid_tags:
            warnings.append(f"{claim_id}: citation does not exist in evidence {', '.join(invalid_tags)}")

        if claim.tags and not valid_tags:
            return ClaimVerificationResult(
                claim_id=claim_id,
                claim_text=claim.text,
                cited_tag=cited_tag,
                status=ClaimStatus.UNVERIFIED,
                confidence_score=0.0,
                explanation=f"Citation tags {', '.join(invalid_tags)} do not point to any evidence.",
            )

        # Valid citation present -> check only against cited source (ensuring provenance fidelity).
        # No citation -> search across all evidence to suggest appropriate source.
        candidate_tags = valid_tags or list(evidence_by_tag)
        best_tag, best_score, best_snippet = None, 0.0, ""
        for tag in candidate_tags:
            score, snippet = self._best_match(claim.text, evidence_by_tag[tag])
            if best_tag is None or score > best_score:
                best_tag, best_score, best_snippet = tag, score, snippet

        # Secondary Evidence Fallback: If the assigned tag lacks sufficient evidence,
        # check the remaining evidence in the pool to avoid false penalties when the LLM misassigns an index.
        if valid_tags and best_score < self.support_threshold and len(evidence_by_tag) > 1:
            other_tags = [t for t in evidence_by_tag if t not in valid_tags]
            for tag in other_tags:
                score, snippet = self._best_match(claim.text, evidence_by_tag[tag])
                if score > best_score:
                    best_tag, best_score, best_snippet = tag, score, snippet
                    if score >= self.support_threshold:
                        warnings.append(f"{claim_id}: Citation for {valid_tags} does not match, but evidence was found in {tag}.")
                        
        score = round(max(0.0, min(1.0, best_score)), 4)
        snippet = _truncate(best_snippet) if best_snippet else None

        if score < self.support_threshold:
            source_desc = f"source {', '.join(valid_tags)}" if valid_tags else "any evidence"
            if not valid_tags:
                warnings.append(f"{claim_id}: claim has no citation and does not match evidence")
            return ClaimVerificationResult(
                claim_id=claim_id,
                claim_text=claim.text,
                cited_tag=cited_tag,
                status=ClaimStatus.UNVERIFIED,
                confidence_score=score,
                matched_snippet=snippet,
                explanation=f"Insufficient grounding found in {source_desc} (score {score:.2f} < {self.support_threshold}).",
            )

        if _has_negation(claim.text) != _has_negation(best_snippet):
            return ClaimVerificationResult(
                claim_id=claim_id,
                claim_text=claim.text,
                cited_tag=cited_tag,
                status=ClaimStatus.CONTRADICTED,
                confidence_score=score,
                matched_snippet=snippet,
                explanation=f"Content matches {best_tag} but has opposing assertion/negation polarity.",
            )

        explanation = f"Substantiated by {best_tag} (score {score:.2f})."
        if not valid_tags:
            warnings.append(f"{claim_id}: claim thiếu thẻ trích dẫn (missing citation tag), suggested source {best_tag}")
            explanation = f"Matches {best_tag} (score {score:.2f}) but answer is missing citation tag."
        return ClaimVerificationResult(
            claim_id=claim_id,
            claim_text=claim.text,
            cited_tag=cited_tag,
            status=ClaimStatus.SUPPORTED,
            confidence_score=score,
            matched_snippet=snippet,
            explanation=explanation,
        )

    @staticmethod
    def _status_for(score: float) -> VerificationStatus:
        if score >= PASSED_THRESHOLD:
            return VerificationStatus.PASSED
        if score >= WARNING_THRESHOLD:
            return VerificationStatus.WARNING
        return VerificationStatus.FAILED

    def verify(
        self,
        draft: SynthesizedDraftSchema,
        evidence_list: list[dict[str, Any]],
    ) -> VerificationReportSchema:
        if draft.is_abstained:
            return VerificationReportSchema(
                faithfulness_score=1.0,
                status=VerificationStatus.SKIPPED,
                warnings=[f"Verification skipped: abstention ({draft.abstention_reason or 'no evidence'})."],
            )

        warnings: list[str] = []
        evidence_by_tag = index_evidence_by_tag(evidence_list)
        if not evidence_by_tag:
            warnings.append("No evidence available for verification.")

        claims = extract_claims(draft.draft_answer, min_tokens=self.min_claim_tokens)
        # Advisory claims are only exempt when Synthesizer actually runs in HYBRID mode.
        if draft.generation_mode != "HYBRID":
            for claim in claims:
                claim.is_advisory = False

        results = [
            self._verify_claim(f"claim_{i:03d}", claim, evidence_by_tag, warnings)
            for i, claim in enumerate(claims, start=1)
        ]

        grounded = [r for r, c in zip(results, claims) if not c.is_advisory]
        advisory_count = len(results) - len(grounded)
        supported = sum(r.status == ClaimStatus.SUPPORTED for r in results)
        contradicted = sum(r.status == ClaimStatus.CONTRADICTED for r in results)
        unverified = sum(r.status == ClaimStatus.UNVERIFIED for r in results)

        if advisory_count:
            warnings.append(
                f"{advisory_count} claims in General Knowledge Advisory are not cross-checked against evidence."
            )

        if grounded:
            score = supported / len(grounded)
            status = self._status_for(score)
        else:
            score = 0.0
            status = VerificationStatus.FAILED
            warnings.append("No grounded claims found to verify.")

        return VerificationReportSchema(
            faithfulness_score=score,
            status=status,
            total_claims=len(results),
            supported_claims=supported,
            contradicted_claims=contradicted,
            unverified_claims=unverified,
            claims_detail=results,
            warnings=warnings,
        )

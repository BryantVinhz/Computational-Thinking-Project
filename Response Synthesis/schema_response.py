"""
Module: schema_response.py
Stage 4: Response Synthesis, Evidence Verification, and Traceable Response
Contract Version: 1.0

Defines shared data structures and the interface contract between
Response Synthesis & Orchestration and Evidence Verification & Traceability.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from enum import Enum
from typing import Any


class ClaimStatus(str, Enum):
    """Verification status of an individual claim compared against retrieved evidence."""
    SUPPORTED = "SUPPORTED"          # Clearly supported by the cited evidence
    CONTRADICTED = "CONTRADICTED"    # Contradicts the cited evidence content
    UNVERIFIED = "UNVERIFIED"        # No supporting basis found (potential hallucination)


class VerificationStatus(str, Enum):
    """Overall faithfulness assessment of the generated response."""
    PASSED = "PASSED"                # High reliability (faithfulness_score >= 0.8)
    WARNING = "WARNING"              # Warning: some claims are not fully verified (0.5 <= score < 0.8)
    FAILED = "FAILED"                # Failed: most content is unverified or contradicted (score < 0.5)
    SKIPPED = "SKIPPED"              # Verification skipped (e.g., when Abstention is triggered)


# Synthesis Draft Contract

@dataclass
class SynthesizedDraftSchema:
    """
    Output produced by the Synthesizer module and passed to the Verifier.
    
    Contains the draft answer generated by the LLM based on context and intent,
    along with inline citation tags [1], [2].
    """
    draft_answer: str                           # Raw Markdown answer from the LLM (with [1], [2] tags)
    intent: str                                 # SEARCH | COMPARE | SYNTHESIS
    cited_evidence_ids: list[str] = field(default_factory=list) # Citation tags referenced by the LLM, e.g. ["[1]", "[2]"]
    is_abstained: bool = False                  # True if the Abstention Policy was triggered (insufficient evidence)
    abstention_reason: str | None = None        # Reason for abstention if applicable
    evidence_status: str = "FULL"               # "FULL" | "PARTIAL" | "NONE" (from Retrieval)
    generation_mode: str = "STRICT_RAG"         # "STRICT_RAG" | "HYBRID" | "ABSTENTION"
    generation_metadata: dict[str, Any] = field(default_factory=dict) # model_name, latency, temperature...

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> SynthesizedDraftSchema:
        return cls(
            draft_answer=data.get("draft_answer", ""),
            intent=data.get("intent", "SEARCH"),
            cited_evidence_ids=data.get("cited_evidence_ids", []),
            is_abstained=data.get("is_abstained", False),
            abstention_reason=data.get("abstention_reason"),
            evidence_status=data.get("evidence_status", "FULL"),
            generation_mode=data.get("generation_mode", "STRICT_RAG"),
            generation_metadata=data.get("generation_metadata", {}),
        )


# Verification & Traceability Contract

@dataclass
class ClaimVerificationResult:
    """Verification result for an individual atomic claim."""
    claim_id: str                               # Claim identifier (e.g. "claim_001")
    claim_text: str                             # Claim statement text
    cited_tag: str | None                       # Citation tag attached to this claim (e.g. "[1]")
    status: ClaimStatus                         # SUPPORTED | CONTRADICTED | UNVERIFIED
    confidence_score: float                     # Similarity/support score (0.0 -> 1.0)
    matched_snippet: str | None = None          # Supporting snippet from the evidence
    explanation: str | None = None              # Brief explanation for the verification outcome

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        if isinstance(self.status, ClaimStatus):
            data["status"] = self.status.value
        return data


@dataclass
class VerificationReportSchema:
    """Aggregated report evaluating hallucinations and answer faithfulness."""
    faithfulness_score: float                   # Fraction of grounded claims supported (0.0 -> 1.0)
    status: VerificationStatus                  # PASSED | WARNING | FAILED | SKIPPED
    total_claims: int = 0
    supported_claims: int = 0
    contradicted_claims: int = 0
    unverified_claims: int = 0
    claims_detail: list[ClaimVerificationResult] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "faithfulness_score": round(self.faithfulness_score, 4),
            "status": self.status.value if isinstance(self.status, VerificationStatus) else self.status,
            "total_claims": self.total_claims,
            "supported_claims": self.supported_claims,
            "contradicted_claims": self.contradicted_claims,
            "unverified_claims": self.unverified_claims,
            "claims_detail": [c.to_dict() for c in self.claims_detail],
            "warnings": self.warnings,
        }


@dataclass
class TraceableCitationSchema:
    """Detailed source provenance metadata corresponding to each citation tag [1], [2]."""
    tag: str                                    # Tag displayed in the response, e.g. "[1]"
    chunk_id: str                               # Chunk identifier (e.g. "doc_a1b2c3d4_v1.0_c00001")
    canonical_title: str                        # Canonical title of the document
    heading_path: list[str] = field(default_factory=list) # Section hierarchy: ["Injection", "Remediation"]
    document_id: str = ""                       # Document ID
    version_id: str = ""                        # Document version ID
    file_name: str = ""                         # Original file name
    file_format: str = ""                       # PDF | MARKDOWN | CSV | JSON
    location_summary: str = ""                  # Concise location (e.g. "Page 14, Lines 12-25")
    locator: dict[str, Any] = field(default_factory=dict) # Detailed coordinates from the Provenance database
    snippet: str = ""                           # Short representative excerpt for preview

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


# Final Response Envelope Contract

@dataclass
class FinalResponseEnvelope:
    """
    Final output of the end-to-end RAG system (Stage 4 complete),
    returned to the UI, API, or end user.
    """
    schema_version: str = "1.0"
    status: str = "ok"                          # "ok" | "abstained" | "clarification_needed" | "error"
    original_query: str = ""                    # Raw query from the user
    resolved_query: str = ""                    # Query resolved after Query Understanding
    intent: str = "SEARCH"                      # SEARCH | COMPARE | SYNTHESIS
    final_answer_markdown: str = ""             # Complete Markdown answer (with Footnotes appended)
    verification: VerificationReportSchema | None = None # Faithfulness verification report
    citations: list[TraceableCitationSchema] = field(default_factory=list) # List of cited sources
    raw_draft: SynthesizedDraftSchema | None = None # Raw synthesis draft (for audit/debugging)
    metadata: dict[str, Any] = field(default_factory=dict) # Performance metrics (timing, counts...)

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "status": self.status,
            "original_query": self.original_query,
            "resolved_query": self.resolved_query,
            "intent": self.intent,
            "final_answer_markdown": self.final_answer_markdown,
            "verification": self.verification.to_dict() if self.verification else None,
            "citations": [c.to_dict() for c in self.citations],
            "raw_draft": self.raw_draft.to_dict() if self.raw_draft else None,
            "metadata": self.metadata,
        }

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), ensure_ascii=False, indent=indent)

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from enum import Enum
from typing import Any


class ClaimStatus(str, Enum):
    """Verification status of each atomic claim checked against Evidence."""
    SUPPORTED = "SUPPORTED"          # Clearly grounded by cited evidence
    CONTRADICTED = "CONTRADICTED"    # Conflicting / contradicting evidence content
    UNVERIFIED = "UNVERIFIED"        # No supporting grounding found (potential hallucination)


class VerificationStatus(str, Enum):
    """Overall assessment of answer faithfulness."""
    PASSED = "PASSED"                # High confidence standard (faithfulness_score >= 0.8)
    WARNING = "WARNING"              # Warning: some claims are not fully verified (0.5 <= score < 0.8)
    FAILED = "FAILED"                # Failed: majority of content is ungrounded or contradicted (score < 0.5)
    SKIPPED = "SKIPPED"              # Verification skipped (e.g., when Abstention is triggered)



# 1. SYNTHESIS OUTPUT CONTRACT (SYNTHESIS DRAFT)
@dataclass
class SynthesizedDraftSchema:
    """
    Output generated by Synthesizer module and handed over to Verifier.
    
    Contains answer draft generated by LLM based on context and intent,
    along with inline citation tags [1], [2].
    """
    draft_answer: str                           # Raw Markdown answer from LLM (with tags [1], [2])
    intent: str                                 # SEARCH | COMPARE | SYNTHESIS
    cited_evidence_ids: list[str] = field(default_factory=list) # List of tags cited by LLM, e.g.: ["[1]", "[2]"]
    is_abstained: bool = False                  # True if Abstention Policy is triggered (insufficient evidence)
    abstention_reason: str | None = None        # Abstention reason if any
    evidence_status: str = "FULL"               # "FULL" | "PARTIAL" | "NONE" (received from Retrieval)
    generation_mode: str = "STRICT_RAG"         # "STRICT_RAG" | "HYBRID" | "ABSTENTION"
    generation_metadata: dict[str, Any] = field(default_factory=dict) # model_name, latency, temperature...

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> SynthesizedDraftSchema:
        return cls(
            draft_answer=data.get("draft_answer", ""),
            intent=data.get("intent", "SEARCH"),
            cited_evidence_ids=data.get("cited_evidence_ids", []),
            is_abstained=data.get("is_abstained", False),
            abstention_reason=data.get("abstention_reason"),
            evidence_status=data.get("evidence_status", "FULL"),
            generation_mode=data.get("generation_mode", "STRICT_RAG"),
            generation_metadata=data.get("generation_metadata", {}),
        )



# 2. VERIFICATION & TRACEABILITY CONTRACT
@dataclass
class ClaimVerificationResult:
    """Verification result for an individual atomic claim."""
    claim_id: str                               # Claim identifier (e.g.: "claim_001")
    claim_text: str                             # Claim text content
    cited_tag: str | None                       # Citation tag attached to this claim (e.g.: "[1]")
    status: ClaimStatus                         # SUPPORTED | CONTRADICTED | UNVERIFIED
    confidence_score: float                     # Confidence / similarity score (0.0 -> 1.0)
    matched_snippet: str | None = None          # Supporting snippet from Evidence
    explanation: str | None = None              # Brief explanation of the evaluation

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        if isinstance(self.status, ClaimStatus):
            data["status"] = self.status.value
        return data


@dataclass
class VerificationReportSchema:
    """Comprehensive verification report on hallucination and faithfulness."""
    faithfulness_score: float                   # Percentage of verified claims (0.0 -> 1.0)
    status: VerificationStatus                  # PASSED | WARNING | FAILED | SKIPPED
    total_claims: int = 0
    supported_claims: int = 0
    contradicted_claims: int = 0
    unverified_claims: int = 0
    claims_detail: list[ClaimVerificationResult] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "faithfulness_score": round(self.faithfulness_score, 4),
            "status": self.status.value if isinstance(self.status, VerificationStatus) else self.status,
            "total_claims": self.total_claims,
            "supported_claims": self.supported_claims,
            "contradicted_claims": self.contradicted_claims,
            "unverified_claims": self.unverified_claims,
            "claims_detail": [c.to_dict() for c in self.claims_detail],
            "warnings": self.warnings,
        }


@dataclass
class TraceableCitationSchema:
    """Detailed provenance tracking information corresponding to citation tags [1], [2]."""
    tag: str                                    # Display tag in text, e.g.: "[1]"
    chunk_id: str                               # Chunk identifier (e.g.: "doc_a1b2c3d4_v1.0_c00001")
    canonical_title: str                        # Canonical title of document
    heading_path: list[str] = field(default_factory=list) # Section hierarchy: ["Injection", "Remediation"]
    document_id: str = ""                       # Document ID
    version_id: str = ""                        # Document version ID
    file_name: str = ""                         # Source file name
    file_format: str = ""                       # PDF | MARKDOWN | CSV | JSON
    location_summary: str = ""                  # Concise location summary (e.g.: "Page 14, Lines 12-25" or "BBox: [..]")
    locator: dict[str, Any] = field(default_factory=dict) # Coordinate details from Provenance database
    snippet: str = ""                           # Representative source snippet for preview

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)



# 3. END-TO-END SYSTEM OUTPUT CONTRACT (FINAL RESPONSE ENVELOPE)
@dataclass
class FinalResponseEnvelope:
    """
    Final output of the entire RAG System (Stage 4 completed).
    Returned to UI / API or end user.
    """
    schema_version: str = "1.0"
    status: str = "ok"                          # "ok" | "abstained" | "clarification_needed" | "error"
    original_query: str = ""                    # Original user query
    resolved_query: str = ""                    # Query after resolution via Query Understanding
    intent: str = "SEARCH"                      # SEARCH | COMPARE | SYNTHESIS
    final_answer_markdown: str = ""             # Complete Markdown answer (with Footnotes at end)
    verification: VerificationReportSchema | None = None # Verification report
    citations: list[TraceableCitationSchema] = field(default_factory=list) # List of cited sources
    raw_draft: SynthesizedDraftSchema | None = None # Original synthesis draft (used for audit/debug)
    metadata: dict[str, Any] = field(default_factory=dict) # Performance metrics (timing, token count...)

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "status": self.status,
            "original_query": self.original_query,
            "resolved_query": self.resolved_query,
            "intent": self.intent,
            "final_answer_markdown": self.final_answer_markdown,
            "verification": self.verification.to_dict() if self.verification else None,
            "citations": [c.to_dict() for c in self.citations],
            "raw_draft": self.raw_draft.to_dict() if self.raw_draft else None,
            "metadata": self.metadata,
        }

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), ensure_ascii=False, indent=indent)

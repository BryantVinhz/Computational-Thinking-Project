"""
Module: schema_response.py
Stage 4: Response Synthesis, Evidence Verification, and Traceable Response
Contract Version: 1.0

Defines unified data structures and the Interface Contract
between Response Synthesis & Orchestration and Evidence Verification & Traceability.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from enum import Enum
from typing import Any


class ClaimStatus(str, Enum):
    """Verification status of an individual atomic claim checked against evidence."""
    SUPPORTED = "SUPPORTED"
    CONTRADICTED = "CONTRADICTED"
    UNVERIFIED = "UNVERIFIED"


class VerificationStatus(str, Enum):
    """Overall faithfulness assessment of the synthesized response."""
    PASSED = "PASSED"
    WARNING = "WARNING"
    FAILED = "FAILED"
    SKIPPED = "SKIPPED"


@dataclass
class SynthesizedDraftSchema:
    """
    Output produced by the Synthesizer and passed to the Verifier.
    
    Contains the draft answer generated by the LLM based on context and intent,
    along with inline citation tags [1], [2].
    """
    draft_answer: str
    intent: str
    cited_evidence_ids: list[str] = field(default_factory=list)
    is_abstained: bool = False
    abstention_reason: str | None = None
    evidence_status: str = "FULL"
    generation_mode: str = "STRICT_RAG"
    generation_metadata: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> SynthesizedDraftSchema:
        return cls(
            draft_answer=data.get("draft_answer", ""),
            intent=data.get("intent", "SEARCH"),
            cited_evidence_ids=data.get("cited_evidence_ids", []),
            is_abstained=data.get("is_abstained", False),
            abstention_reason=data.get("abstention_reason"),
            evidence_status=data.get("evidence_status", "FULL"),
            generation_mode=data.get("generation_mode", "STRICT_RAG"),
            generation_metadata=data.get("generation_metadata", {}),
        )


@dataclass
class ClaimVerificationResult:
    """Verification result for an individual sentence / atomic claim."""
    claim_id: str
    claim_text: str
    cited_tag: str | None
    status: ClaimStatus
    confidence_score: float
    matched_snippet: str | None = None
    explanation: str | None = None

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        if isinstance(self.status, ClaimStatus):
            data["status"] = self.status.value
        return data


@dataclass
class VerificationReportSchema:
    """Aggregated hallucination and faithfulness verification report for the response."""
    faithfulness_score: float
    status: VerificationStatus
    total_claims: int = 0
    supported_claims: int = 0
    contradicted_claims: int = 0
    unverified_claims: int = 0
    claims_detail: list[ClaimVerificationResult] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "faithfulness_score": round(self.faithfulness_score, 4),
            "status": self.status.value if isinstance(self.status, VerificationStatus) else self.status,
            "total_claims": self.total_claims,
            "supported_claims": self.supported_claims,
            "contradicted_claims": self.contradicted_claims,
            "unverified_claims": self.unverified_claims,
            "claims_detail": [c.to_dict() for c in self.claims_detail],
            "warnings": self.warnings,
        }


@dataclass
class TraceableCitationSchema:
    """Detailed provenance traceability metadata corresponding to each citation tag [1], [2]."""
    tag: str
    chunk_id: str
    canonical_title: str
    heading_path: list[str] = field(default_factory=list)
    document_id: str = ""
    version_id: str = ""
    file_name: str = ""
    file_format: str = ""
    location_summary: str = ""
    locator: dict[str, Any] = field(default_factory=dict)
    snippet: str = ""

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class FinalResponseEnvelope:
    """
    Final output of the complete RAG System (Stage 4 completed).
    Returned to the UI / API or end user.
    """
    schema_version: str = "1.0"
    status: str = "ok"
    original_query: str = ""
    resolved_query: str = ""
    intent: str = "SEARCH"
    final_answer_markdown: str = ""
    verification: VerificationReportSchema | None = None
    citations: list[TraceableCitationSchema] = field(default_factory=list)
    raw_draft: SynthesizedDraftSchema | None = None
    metadata: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "status": self.status,
            "original_query": self.original_query,
            "resolved_query": self.resolved_query,
            "intent": self.intent,
            "final_answer_markdown": self.final_answer_markdown,
            "verification": self.verification.to_dict() if self.verification else None,
            "citations": [c.to_dict() for c in self.citations],
            "raw_draft": self.raw_draft.to_dict() if self.raw_draft else None,
            "metadata": self.metadata,
        }

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), ensure_ascii=False, indent=indent)

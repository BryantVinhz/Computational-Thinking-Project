from path import PROVENANCE_OUT_DIR

POS_PATH = CURRENT_DIR / "raw_positive_100.json"
TRAP_PATH = CURRENT_DIR / "raw_traps_25.json"
FINAL_PATH = CURRENT_DIR / "retrieval_eval_dataset.json"


def resolve_exact_span(full_text: str, raw_span: str) -> tuple[int, int, str] | None:
    """Find the exact [start_offset, end_offset) position in normalized_text, automatically removing redundant LLM escapes."""
    cleaned = (raw_span or "").strip()
    if not cleaned:
        return None

    # 1. Try 100% verbatim match
    pos = full_text.find(cleaned)
    if pos != -1:
        return pos, pos + len(cleaned), cleaned

    # 2. Try removing redundant escape characters generated by the LLM (\(, \), \:, \\)
    unescaped = (
        cleaned.replace(r"\(", "(")
        .replace(r"\)", ")")
        .replace(r"\:", ":")
        .replace("\\\\", "\\")
    )
    pos = full_text.find(unescaped)
    if pos != -1:
        return pos, pos + len(unescaped), unescaped

    # 3. Try case-insensitive match (e.g., java.lang.string -> java.lang.String)
    match = re.search(re.escape(unescaped), full_text, flags=re.IGNORECASE)
    if match:
        matched_sub = full_text[match.start() : match.end()]
        return match.start(), match.end(), matched_sub

    return None


def finalize() -> None:
    db_path = PROVENANCE_OUT_DIR / "semantic" / "workspace_data.db"
    conn = sqlite3.connect(str(db_path))
    block_texts = {
        row[0]: (row[1] or "")
        for row in conn.execute("SELECT normalized_id, normalized_text FROM normalized_blocks").fetchall()
    }
    conn.close()

    positives = json.loads(POS_PATH.read_text(encoding="utf-8"))
    traps = json.loads(TRAP_PATH.read_text(encoding="utf-8"))

    repaired_count = 0
    errors: list[str] = []

    for item in positives:
        for unit in item.get("evidence_units", []):
            for sp in unit.get("spans", []):
                bid = sp["normalized_block_id"]
                full_text = block_texts.get(bid, "")
                raw_exact = (sp.get("exact_span") or "").strip()

                resolved = resolve_exact_span(full_text, raw_exact)
                if resolved is None:
                    errors.append(f"[{item['query_id']} - {unit['unit_id']}] Failed to match exact_span in {bid}")
                else:
                    start, end, canonical_span = resolved
                    if canonical_span != raw_exact:
                        repaired_count += 1
                    sp["start_offset"] = start
                    sp["end_offset"] = end
                    sp["exact_span"] = canonical_span

    if errors:
        print(f"Detected {len(errors)} errors that could not be automatically fixed:")
        for err in errors:
            print("  -", err)
        return

    full_dataset = positives + traps
    # Sort again in exact order from RET_001 -> RET_125
    full_dataset.sort(key=lambda x: x["query_id"])

    FINAL_PATH.write_text(json.dumps(full_dataset, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Done! Automatically normalized {repaired_count} spans with redundant escapes and packaged {len(full_dataset)} standard samples at:")
    print(f"  => {FINAL_PATH}")


if __name__ == "__main__":
    finalize()